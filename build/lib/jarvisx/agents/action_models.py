"""Data Models for Phase 91 Autonomous Mission Brain (Layer 6 - Cognition & Agents)."""

from __future__ import annotations
from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Callable, Dict, List, Optional


class RiskLevel(str, Enum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class PolicyDecision(str, Enum):
    ALLOW = "ALLOW"
    ASK_USER = "ASK_USER"
    BLOCK = "BLOCK"


@dataclass
class Capability:
    """Self-describing capability registered in the system."""
    name: str
    description: str
    category: str
    inputs: List[str]
    risk_level: RiskLevel
    permissions: List[str]
    handler: Callable[..., Any]
    enabled: bool = True

    def to_dict(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "description": self.description,
            "category": self.category,
            "inputs": self.inputs,
            "risk_level": self.risk_level.value if isinstance(self.risk_level, RiskLevel) else self.risk_level,
            "permissions": self.permissions,
            "enabled": self.enabled,
        }


@dataclass
class ActionProposal:
    """Action proposed by the planner."""
    capability_name: str
    arguments: Dict[str, Any]
    rationale: str
    expected_outcome: str
    step_index: int = 1


@dataclass
class ExecutionResult:
    """Result of an executed action."""
    action_name: str
    status: str  # SUCCESS, FAILED, BLOCKED
    output: Any
    duration_sec: float
    error: Optional[str] = None
    artifacts_created: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "action_name": self.action_name,
            "status": self.status,
            "output": self.output if isinstance(self.output, (dict, list, str, int, float, bool)) else str(self.output),
            "duration_sec": self.duration_sec,
            "error": self.error,
            "artifacts_created": self.artifacts_created,
        }


@dataclass
class ReflectionResult:
    """Evaluation result generated by the reflection engine."""
    goal_progress: float  # 0.0 to 1.0
    is_goal_achieved: bool
    requires_replanning: bool
    what_succeeded: List[str]
    what_failed: List[str]
    recommended_next_action: Optional[str] = None
    reflection_notes: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "goal_progress": self.goal_progress,
            "is_goal_achieved": self.is_goal_achieved,
            "requires_replanning": self.requires_replanning,
            "what_succeeded": self.what_succeeded,
            "what_failed": self.what_failed,
            "recommended_next_action": self.recommended_next_action,
            "reflection_notes": self.reflection_notes,
        }
