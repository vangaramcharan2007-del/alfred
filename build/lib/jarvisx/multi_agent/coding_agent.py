"""Coding & Software Engineering Agent for Phase 96 Multi-Agent Operating System."""

from __future__ import annotations
import time
from pathlib import Path
from typing import Dict, Any, Optional
from jarvisx.multi_agent.agent_bus import AgentCommunicationBus
from jarvisx.multi_agent.models import AgentCapability, AgentMessage, AgentRole, MessageType, SubTask


class CodingAgent:
    """Specialized Engineering & Software Agent.
    Generates modules, test suites, and refactoring within authorized project scope.
    """

    def __init__(self, bus: AgentCommunicationBus):
        self.bus = bus
        self.capability = AgentCapability(
            name="CodingAgent",
            role=AgentRole.CODER,
            skills=["python_code", "pytest_generation", "refactoring", "fastapi"],
            permission_scope="project_dir"
        )
        self.bus.subscribe("CODER", self.handle_task_request)

    def handle_task_request(self, message: AgentMessage) -> None:
        if message.msg_type == MessageType.TASK_REQUEST:
            task_dict = message.payload.get("task", {})
            subtask = SubTask(
                id=task_dict.get("id", "code_01"),
                title=task_dict.get("title", "Engineering Task"),
                agent_role=AgentRole.CODER,
                parameters=task_dict.get("parameters", {})
            )
            result = self.execute_coding(subtask)
            self.bus.publish(AgentMessage(
                id=f"code_out_{int(time.time()*1000)}",
                sender="CODER",
                recipient="ALFRED",
                msg_type=MessageType.TASK_RESULT if subtask.status == "COMPLETED" else MessageType.ERROR_REPORT,
                topic="CODE_GENERATED" if subtask.status == "COMPLETED" else "CODE_FAILED",
                payload={"task_id": subtask.id, "result": result},
                timestamp=time.time()
            ))

    def execute_coding(self, task: SubTask) -> Dict[str, Any]:
        """Synthesize source code and test files."""
        proj_name = task.parameters.get("project_name", "weather_microservice")
        dest_dir = Path("var/missions") / proj_name
        dest_dir.mkdir(parents=True, exist_ok=True)

        print(f"  [Coder Agent]: Synthesizing software code for '{task.title}' in {dest_dir}...")

        # 1. Generate Application Module
        app_file = dest_dir / "app.py"
        app_code = """\"\"\"FastAPI Microservice generated by Jarvis X Coding Agent.\"\"\"
from fastapi import FastAPI

app = FastAPI(title="WeatherService", version="1.0.0")

@app.get("/")
def get_root():
    return {"service": "WeatherService", "status": "ONLINE"}

@app.get("/weather/{city}")
def get_weather(city: str):
    return {"city": city, "temperature_c": 24.5, "condition": "Sunny"}
"""
        app_file.write_text(app_code, encoding="utf-8")

        # 2. Generate Unit Test Module
        test_file = dest_dir / "test_app.py"
        test_code = """\"\"\"Unit test suite for WeatherService.\"\"\"
from app import app
from fastapi.testclient import TestClient

client = TestClient(app)

def test_root():
    res = client.get("/")
    assert res.status_code == 200
    assert res.json()["status"] == "ONLINE"

def test_weather_city():
    res = client.get("/weather/Tokyo")
    assert res.status_code == 200
    assert res.json()["city"] == "Tokyo"
"""
        test_file.write_text(test_code, encoding="utf-8")

        task.status = "COMPLETED"
        res = {
            "source_file": str(app_file),
            "test_file": str(test_file),
            "lines_generated": len(app_code.splitlines()) + len(test_code.splitlines()),
            "status": "SUCCESS"
        }
        task.result = res
        return res
